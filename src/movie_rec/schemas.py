def assert_schema(df: DataFrame, schema: StructType, name: str) -> None:
    """Fail when ``df`` does not carry exactly the columns and types of ``schema``.

    Parquet does not preserve nullability, so this compares names and data
    types only. Extra or reordered columns are errors: downstream code selects
    by name and relies on the agreed contract.
    """
    actual = [(f.name, f.dataType) for f in df.schema.fields]
    expected = [(f.name, f.dataType) for f in schema.fields]
    if actual != expected:
        raise ValueError(
            f"{name} schema mismatch\n  expected: {expected}\n  actual:   {actual}"
        )


def assert_unique_key(df: DataFrame, keys: list[str], name: str) -> None:
    """Fail when ``keys`` is not unique in ``df``; print a few offending rows."""
    dupes = df.groupBy(*keys).count().filter(F.col("count") > 1).limit(5).collect()
    if dupes:
        sample = [row.asDict() for row in dupes]
        raise ValueError(f"{name}: duplicate key {keys}, examples: {sample}")


def assert_no_nulls(df: DataFrame, columns: list[str], name: str) -> None:
    """Fail when any of ``columns`` contains a null value."""
    condition = reduce(or_, (F.col(c).isNull() for c in columns))
    bad = df.filter(condition).limit(5).collect()
    if bad:
        sample = [row.asDict() for row in bad]
        raise ValueError(f"{name}: null values in {columns}, examples: {sample}")


def assert_allowed_values(
    df: DataFrame, column: str, allowed: tuple[str, ...], name: str
) -> None:
    """Fail when ``column`` holds a value outside ``allowed``."""
    bad = (
        df.select(column)
        .distinct()
        .filter(~F.col(column).isin(list(allowed)))
        .limit(10)
        .collect()
    )
    if bad:
        values = [row[0] for row in bad]
        raise ValueError(f"{name}: unexpected {column} values {values}")
